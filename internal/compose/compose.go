// Package compose renders a blueprint into docker compose and restic configuration files.
package compose

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/sapper-unbuilt/sapper/internal/blueprint"
	"github.com/sapper-unbuilt/sapper/internal/catalog"
)

// File is the subset of the compose specification sapper writes.
type File struct {
	Name     string             `yaml:"name"`
	Services map[string]Service `yaml:"services"`
}

// Service is one compose service.
type Service struct {
	Image       string            `yaml:"image"`
	Restart     string            `yaml:"restart"`
	Ports       []string          `yaml:"ports"`
	Volumes     []string          `yaml:"volumes"`
	Environment map[string]string `yaml:"environment,omitempty"`
	SecurityOpt []string          `yaml:"security_opt,omitempty"`
}

// Build converts a validated blueprint into a compose file. Ports bind to 127.0.0.1.
func Build(bp *blueprint.Blueprint) (File, error) {
	f := File{Name: bp.Fortress, Services: map[string]Service{}}
	for _, name := range bp.AppNames() {
		app := bp.Apps[name]
		def, ok := catalog.Lookup(name)
		if !ok {
			return File{}, fmt.Errorf("app %s: not in catalogue", name)
		}
		svc := Service{
			Image:       def.Image,
			Restart:     "unless-stopped",
			Ports:       []string{fmt.Sprintf("127.0.0.1:%d:%d", app.Port, def.Port)},
			Environment: def.Env,
			// Stop setuid binaries in an image from regaining privileges after a compromise.
			SecurityOpt: []string{"no-new-privileges:true"},
		}
		for _, m := range def.Mounts {
			svc.Volumes = append(svc.Volumes, bp.HostPath(app.Volumes[m.Name])+":"+m.ContainerPath)
		}
		f.Services[name] = svc
	}
	return f, nil
}

// Artifacts are the rendered files keyed by file name inside the output directory.
type Artifacts map[string][]byte

// Render produces every file sapper writes into .sapper/.
func Render(bp *blueprint.Blueprint) (Artifacts, error) {
	f, err := Build(bp)
	if err != nil {
		return nil, err
	}
	y, err := yaml.Marshal(f)
	if err != nil {
		return nil, err
	}
	header := "# Generated by sapper from " + blueprint.FileName + ". Edits are overwritten by `sapper build`.\n"
	out := Artifacts{"docker-compose.yml": append([]byte(header), y...)}

	if err := blueprint.CheckEnvValue(bp.RepoLocation()); err != nil {
		return nil, fmt.Errorf("restic repository %q: %w; move the blueprint or repository to a plain path", bp.RepoLocation(), err)
	}
	var env strings.Builder
	env.WriteString(header)
	fmt.Fprintf(&env, "RESTIC_REPOSITORY=%s\n", bp.RepoLocation())
	fmt.Fprintf(&env, "# The password is read from $%s at run time and never written here.\n", bp.Backup.PasswordEnv)
	out["restic.env"] = []byte(env.String())

	var paths strings.Builder
	for _, p := range bp.VolumePaths() {
		paths.WriteString(p + "\n")
	}
	out["backup-paths.txt"] = []byte(paths.String())

	if bp.Drill.Schedule != "" {
		// cron turns an unescaped '%' into a newline and a newline ends the entry, so either
		// in the blueprint directory would let the path smuggle a second command into the crontab.
		if strings.ContainsAny(bp.Dir, "%\n\r\x00") {
			return nil, fmt.Errorf("drill.schedule: blueprint directory %q contains '%%' or a control character, which cron cannot run safely; move the blueprint", bp.Dir)
		}
		out["drill.cron"] = []byte(fmt.Sprintf("%s%s cd %s && sapper breach\n", header, bp.Drill.Schedule, shellQuote(bp.Dir)))
	}
	return out, nil
}

// Write stores artifacts in dir with private permissions.
func Write(dir string, a Artifacts) error {
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return err
	}
	// MkdirAll leaves an existing directory's mode alone; tighten it.
	if err := os.Chmod(dir, 0o700); err != nil {
		return err
	}
	for name, data := range a {
		if err := writeAtomic(filepath.Join(dir, name), data); err != nil {
			return err
		}
	}
	return nil
}

func writeAtomic(path string, data []byte) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), ".tmp-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Chmod(0o600); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}

func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
